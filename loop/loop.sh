run_claude_session() {
  local iter="$1"
  local prompt_file="$2"
  local log_file="$STATE_DIR/session-${iter}.log"
  local prompt
  prompt="$(cat "$prompt_file")"

  local mode=headless
  local -a command
  # Claude loads .claude/agents+settings from cwd=hub; product code via --add-dir.
  local -a add_dir_args=(--add-dir "$PROJECT_ROOT")
  if [[ "$HEADLESS" == "1" ]]; then
    echo "==> headless → $log_file (claude cwd=$HUB_ROOT add-dir=$PROJECT_ROOT)"
    # IMPORTANT: prompt must follow -p immediately. --add-dir is variadic and
    # would swallow the prompt text as another "directory" if placed before it.
    command=("$CLAUDE" -p "$prompt" \
      --output-format stream-json \
      --include-partial-messages \
      --verbose \
      "${add_dir_args[@]}" \
      "${PERM_ARGS[@]}" "${MODEL_ARGS[@]}" "${EXTRA_ARGS[@]}")
  else
    mode=interactive
    echo "==> interactive — /exit after FINISH (claude cwd=$HUB_ROOT add-dir=$PROJECT_ROOT)"
    command=("$CLAUDE" "$prompt" "${add_dir_args[@]}" "${PERM_ARGS[@]}" "${MODEL_ARGS[@]}" "${EXTRA_ARGS[@]}")
  fi

  set +e
  if [[ "$HEADLESS" == "1" ]]; then
    (cd "$HUB_ROOT" && python3 "$SESSION_WRAPPER" run-session \
      --mode "$mode" \
      --session-id "$iter" \
      --timeout "$EPIC_SESSION_TIMEOUT_SEC" \
      --kill-grace "$EPIC_SESSION_KILL_GRACE_SEC" \
      ${EPIC_STATUS_HEARTBEAT_SEC:+--heartbeat-sec "$EPIC_STATUS_HEARTBEAT_SEC"} \
      ${EPIC_STREAM_IDLE_TIMEOUT_SEC:+--idle-timeout "$EPIC_STREAM_IDLE_TIMEOUT_SEC"} \
      --log "$log_file" \
      ${SESSION_MODEL:+--expected-model "$SESSION_MODEL"} \
      -- "${command[@]}") | python3 "$STREAM_FILTER"
    rc="${PIPESTATUS[0]}"
  else
    (cd "$HUB_ROOT" && python3 "$SESSION_WRAPPER" run-session \
      --mode "$mode" \
      --session-id "$iter" \
      --timeout "$EPIC_SESSION_TIMEOUT_SEC" \
      --kill-grace "$EPIC_SESSION_KILL_GRACE_SEC" \
      ${EPIC_STATUS_HEARTBEAT_SEC:+--heartbeat-sec "$EPIC_STATUS_HEARTBEAT_SEC"} \
      ${EPIC_STREAM_IDLE_TIMEOUT_SEC:+--idle-timeout "$EPIC_STREAM_IDLE_TIMEOUT_SEC"} \
      --log "$log_file" \
      ${SESSION_MODEL:+--expected-model "$SESSION_MODEL"} \
      -- "${command[@]}")
    rc=$?
  fi
  # HARD: do NOT `set -e` before return — under bash errexit a non-zero
  # `return` from a function aborts the whole loop.sh (skips record-session /
  # transient retry). Caller owns set +e / set -e around this call.
  return "$rc"
}

resolve_dsh_bin() {
  if [[ -n "${DSH_BIN:-}" && -x "$DSH_BIN" ]]; then
    DSH_COMMAND=("$DSH_BIN")
    return 0
  fi

  local resolver="${DSH_RESOLVER:-$HUB_ROOT/dsh/bin/which-dsh.sh}"
  if [[ -x "$resolver" ]]; then
    local -a resolved
    local executable
    mapfile -t resolved < <("$resolver")
    if [[ ${#resolved[@]} -gt 0 ]]; then
      executable="${resolved[0]}"
      if [[ "$executable" != */* ]]; then
        executable="$(command -v "$executable" || true)"
      fi
      if [[ -n "$executable" && -x "$executable" ]]; then
        DSH_COMMAND=("$executable" "${resolved[@]:1}")
        return 0
      fi
      echo "dsh binary not found: ${resolved[*]}" >&2
      return 127
    fi
  fi

  echo "dsh binary not found; set DSH_BIN or install @deepseek-ai/dsh" >&2
  return 127
}

DSH_COMMAND=()


run_dsh_session() {
  local iter="$1"
  local prompt_file="$2"
  local log_file="$STATE_DIR/session-${iter}.log"
  local prompt
  local dsh_rc
  prompt="$(cat "$prompt_file")"

  if resolve_dsh_bin; then
    dsh_rc=0
  else
    dsh_rc=$?
  fi
  if [[ $dsh_rc -ne 0 || ${#DSH_COMMAND[@]} -eq 0 ]]; then
    echo "==> HALT: dsh binary not found; no Claude fallback" >&2
    return 127
  fi

  local profile_override
  profile_override="$(echo "${EXTRAS_JSON:-{}}" | python3 -c 'import json,sys; print(json.load(sys.stdin).get("dsh_profile") or "epic-implement")' 2>/dev/null || echo epic-implement)"
  local profile="$profile_override"
  local -a command=("${DSH_COMMAND[@]}" --profile "$profile" --no-open "$prompt")
  local rc
  if (cd "$PROJECT_ROOT" && python3 "$SESSION_WRAPPER" run-session \
    --mode headless \
    --session-id "$iter" \
    --timeout "$EPIC_SESSION_TIMEOUT_SEC" \
    --kill-grace "$EPIC_SESSION_KILL_GRACE_SEC" \
    ${EPIC_STATUS_HEARTBEAT_SEC:+--heartbeat-sec "$EPIC_STATUS_HEARTBEAT_SEC"} \
    ${EPIC_STREAM_IDLE_TIMEOUT_SEC:+--idle-timeout "$EPIC_STREAM_IDLE_TIMEOUT_SEC"} \
    --log "$log_file" \
    -- "${command[@]}"); then
    rc=0
  else
    rc=$?
  fi
  return "$rc"
}

run_agent_session() {
  local iter="$1"
  local prompt_file="$2"
  local log_file="$STATE_DIR/session-${iter}.log"
  local runtime_id="${EPIC_RUNTIME_RESOLVED:-claude}"
  local extras_json="{}"
  local -a command=()
  local rc=0
  local session_cwd="$HUB_ROOT"

  if [[ "$runtime_id" == "dsh" ]]; then
    extras_json="${EXTRAS_JSON:-{}}"
    session_cwd="$PROJECT_ROOT"
  elif [[ "$runtime_id" == "codex" ]]; then
    extras_json="$(PROJECT_ROOT="$PROJECT_ROOT" python3 -c 'import json,os; print(json.dumps({"project_root": os.environ["PROJECT_ROOT"]}))')"
    session_cwd="$PROJECT_ROOT"
  fi

  local argv_json=""
  argv_json="$(python3 -m loop.runtime.dispatch print-argv \
    --runtime "$runtime_id" \
    --prompt-file "$prompt_file" \
    --phase "${LOOP_PHASE:-IMPLEMENT}" \
    ${SESSION_MODEL:+--model "$SESSION_MODEL"} \
    --extras-json "$extras_json")" || {
    echo "==> HALT: dispatch print-argv failed for runtime=$runtime_id" >&2
    return 2
  }
  if [[ -z "$argv_json" ]]; then
    echo "==> HALT: dispatch print-argv empty for runtime=$runtime_id" >&2
    return 2
  fi
  mapfile -d '' -t command < <(printf '%s' "$argv_json" | python3 -c '
import json, sys
for part in json.load(sys.stdin):
    sys.stdout.buffer.write(part.encode("utf-8") + b"\0")
')

  if [[ "$runtime_id" == "claude" ]]; then
    command[0]="$CLAUDE"
    command+=("--add-dir" "$PROJECT_ROOT")
    command+=("${PERM_ARGS[@]}" "${EXTRA_ARGS[@]}")
  elif [[ "$runtime_id" == "dsh" ]]; then
    if ! resolve_dsh_bin; then
      echo "==> HALT: dsh binary not found; no Claude fallback" >&2
      return 127
    fi
    command=("${DSH_COMMAND[@]}" "${command[@]:1}")
  fi

  local -a stdin_file_args=()
  local progress_mode="tool_json"
  if [[ "$runtime_id" == "codex" ]]; then
    stdin_file_args=(--stdin-file "$prompt_file")
    progress_mode="codex_json"
  fi

  set +e
  if [[ "$HEADLESS" == "1" ]]; then
    echo "==> headless → $log_file (runtime=$runtime_id cwd=$session_cwd)"
    if [[ "$runtime_id" == "claude" ]]; then
      (cd "$session_cwd" && python3 "$SESSION_WRAPPER" run-session \
        --mode headless \
        --session-id "$iter" \
        --timeout "$EPIC_SESSION_TIMEOUT_SEC" \
        --kill-grace "$EPIC_SESSION_KILL_GRACE_SEC" \
        ${EPIC_STATUS_HEARTBEAT_SEC:+--heartbeat-sec "$EPIC_STATUS_HEARTBEAT_SEC"} \
        ${EPIC_STREAM_IDLE_TIMEOUT_SEC:+--idle-timeout "$EPIC_STREAM_IDLE_TIMEOUT_SEC"} \
        --progress-mode "$progress_mode" \
        --log "$log_file" \
        ${SESSION_MODEL:+--expected-model "$SESSION_MODEL"} \
        -- "${command[@]}") | python3 "$STREAM_FILTER"
      rc="${PIPESTATUS[0]}"
    elif [[ "$runtime_id" == "codex" ]]; then
      (cd "$session_cwd" && python3 "$SESSION_WRAPPER" run-session \
        --mode headless \
        --session-id "$iter" \
        --timeout "$EPIC_SESSION_TIMEOUT_SEC" \
        --kill-grace "$EPIC_SESSION_KILL_GRACE_SEC" \
        ${EPIC_STATUS_HEARTBEAT_SEC:+--heartbeat-sec "$EPIC_STATUS_HEARTBEAT_SEC"} \
        ${EPIC_STREAM_IDLE_TIMEOUT_SEC:+--idle-timeout "$EPIC_STREAM_IDLE_TIMEOUT_SEC"} \
        --progress-mode "$progress_mode" \
        --log "$log_file" \
        ${SESSION_MODEL:+--expected-model "$SESSION_MODEL"} \
        "${stdin_file_args[@]}" \
        -- "${command[@]}") | python3 "$CODEX_STREAM_FILTER"
      rc="${PIPESTATUS[0]}"
    else
      (cd "$session_cwd" && python3 "$SESSION_WRAPPER" run-session \
        --mode headless \
        --session-id "$iter" \
        --timeout "$EPIC_SESSION_TIMEOUT_SEC" \
        --kill-grace "$EPIC_SESSION_KILL_GRACE_SEC" \
        ${EPIC_STATUS_HEARTBEAT_SEC:+--heartbeat-sec "$EPIC_STATUS_HEARTBEAT_SEC"} \
        ${EPIC_STREAM_IDLE_TIMEOUT_SEC:+--idle-timeout "$EPIC_STREAM_IDLE_TIMEOUT_SEC"} \
        --progress-mode "$progress_mode" \
        --log "$log_file" \
        ${SESSION_MODEL:+--expected-model "$SESSION_MODEL"} \
        "${stdin_file_args[@]}" \
        -- "${command[@]}")
      rc=$?
    fi
  else
    echo "==> interactive — /exit after FINISH (runtime=$runtime_id cwd=$session_cwd)"
    (cd "$session_cwd" && python3 "$SESSION_WRAPPER" run-session \
      --mode interactive \
      --session-id "$iter" \
      --timeout "$EPIC_SESSION_TIMEOUT_SEC" \
      --kill-grace "$EPIC_SESSION_KILL_GRACE_SEC" \
      ${EPIC_STATUS_HEARTBEAT_SEC:+--heartbeat-sec "$EPIC_STATUS_HEARTBEAT_SEC"} \
      ${EPIC_STREAM_IDLE_TIMEOUT_SEC:+--idle-timeout "$EPIC_STREAM_IDLE_TIMEOUT_SEC"} \
      --progress-mode "$progress_mode" \
      --log "$log_file" \
      ${SESSION_MODEL:+--expected-model "$SESSION_MODEL"} \
      "${stdin_file_args[@]}" \
      -- "${command[@]}")
    rc=$?
  fi
  return "$rc"
}


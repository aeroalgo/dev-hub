print("==> prepare:", "ok" if r.get("ok") else r.get("reason"))
phase = r.get("phase") or r.get("loop_phase") or ""
step = r.get("armed_step") or ""
if phase or step:
    print("==> working:", (phase or "?"), "step=" + (step or "?"))

find_claude() {
  if [[ -n "${CLAUDE_BIN:-}" && -x "$CLAUDE_BIN" ]]; then
    echo "$CLAUDE_BIN"
    return
  fi
  if command -v claude >/dev/null 2>&1; then
    command -v claude
    return
  fi
  local cand
  cand="$(ls -1d "$HOME"/.cursor/extensions/anthropic.claude-code-*/resources/native-binary/claude 2>/dev/null | sort -V | tail -1 || true)"
  if [[ -n "$cand" && -x "$cand" ]]; then
    echo "$cand"
    return
  fi
  echo "claude binary not found; set CLAUDE_BIN" >&2
  exit 127
}

is_epic_spec() {
  case "$1" in
    decompose-*|plan-*|T-*)
      return 0 ;;
    memory-bank/*/plan/decompose-*|memory-bank/*/plan/plan-*)
      return 0 ;;
    memory-bank/*/plan/decompose-*/index.md)
      return 0 ;;
    */decompose-*|*/plan-*)
      return 0 ;;
    *)
      return 1 ;;
  esac
}

